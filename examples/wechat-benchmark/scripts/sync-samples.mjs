// Mirrors the Node-side bench corpus into pages/bench/samples.js so the
// miniprogram (which can't `fs.read` at runtime) has the same fixtures
// inline. Re-run this after editing benchmark/samples/streaming/*.md.
//
// Usage: node examples/wechat-benchmark/scripts/sync-samples.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, basename } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const exampleRoot = join(__dirname, '..');
const repoRoot = join(exampleRoot, '..', '..');

const SAMPLE_FILES = [
  // Long realistic LLM output (~8KB) — the headline test case for this lib.
  join(repoRoot, 'benchmark', 'samples', 'streaming', 'ai-chat-long.md'),
  // A handful of representative small fixtures from the markdown-it corpus.
  join(repoRoot, 'benchmark', 'samples', 'markdown-it', 'block-tables.md'),
  join(repoRoot, 'benchmark', 'samples', 'markdown-it', 'block-list-nested.md'),
  join(repoRoot, 'benchmark', 'samples', 'markdown-it', 'lorem1.txt'),
];

const samples = SAMPLE_FILES.map((p) => ({
  name: basename(p),
  content: readFileSync(p, 'utf8'),
}));

const banner = `// AUTO-GENERATED by scripts/sync-samples.mjs — do not edit.
// To refresh, run: node examples/wechat-benchmark/scripts/sync-samples.mjs
`;

const body = `
const SAMPLES = ${JSON.stringify(samples, null, 2)};

module.exports = {
  SAMPLES,
  defaultIndex: 0,
};
`;

const out = join(exampleRoot, 'pages', 'bench', 'samples.js');
writeFileSync(out, banner + body);
console.log(`wrote ${samples.length} samples -> ${out}`);
