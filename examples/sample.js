    '',
    '两种页面读取的是同一份示例内容，因此可以直接比较最终节点结构和视觉结果。差异只应来自平台能力，不应来自手工维护了两份不同文案。',
    '',
    '## 代码高亮',
    '',
    '```js',
    'const md = new XMarkdownMini({',
