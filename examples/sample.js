    '',
    '## 一次流式回复会经历什么',
    '',
    '1. 接收增量字符，并保留截至当前的完整 Markdown。',
    '2. 识别由双空行结束的稳定块，只重新解析仍在变化的尾部。',
    '3. 将 token 直接转换成目标平台节点。',
    '   - 微信使用 `tokensToWechat`。',
    '   - 支付宝使用 `tokensToAlipay`。',
